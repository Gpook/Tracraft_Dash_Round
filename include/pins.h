/**
 * @file  pins.h
 * @brief Распиновка LilyGo T-Display-S3-AMOLED 1.75" (панель H0175Y003AM).
 *
 * Источник — pin_config.h из официального репозитория LilyGo:
 * Xinyuan-LilyGO/T-Display-S3-AMOLED-1.43-1.75
 *
 * ВАЖНО про драйвер. В карточке товара LilyGo для 1.75" указан SH8601,
 * но их собственный pin_config.h говорит иное:
 *     H0175Y003AM  // 1.75 inches (CO5300 CST9217)
 *     DO0143FAT01  // 1.43 inches (SH8601 FT3168)
 * То есть SH8601 стоит на 1.43", а на нашей 1.75" — CO5300, тач CST9217.
 * Карточке товара не верим, верим коду вендора.
 * Если экран останется чёрным — собрать env:dash_sh8601 (см. platformio.ini).
 */

#pragma once

// ─── Дисплей: QSPI ───────────────────────────────────────────────────────────
#define LCD_SDIO0        11
#define LCD_SDIO1        13
#define LCD_SDIO2        14
#define LCD_SDIO3        15
#define LCD_SCLK         12
#define LCD_CS           10
#define LCD_RST          17

/// Питание панели. Без HIGH до begin() экран не оживёт.
#define LCD_EN           16

// ─── Геометрия панели ────────────────────────────────────────────────────────
//
// Видимая круглая область — 466x466. Память контроллера — 480x480, поэтому
// нужен сдвиг по колонкам: LilyGo в примерах передаёт col_offset1 = 6.
//
// LilyGo объявляет размер как 473x467 — это шире видимой области и, судя по
// всему, просто неаккуратность. Берём честные 466x466: канва совпадает с
// экраном 1:1, значит фреймбуфер уходит одним полным блитом без пересчёта.
// Если картинка окажется сдвинутой — крутить эти четыре значения.
#define LCD_WIDTH        466
#define LCD_HEIGHT       466
#define LCD_COL_OFFSET   6
#define LCD_ROW_OFFSET   0

// ─── I2C: тач CST9217, RTC PCF8563, зарядник SY6970 ──────────────────────────
#define IIC_SDA          7
#define IIC_SCL          6

/// Общая линия прерывания: тач и PCF8563 висят на одном GPIO.
#define TP_INT           9
#define PCF8563_INT      9

// ─── Прочее ──────────────────────────────────────────────────────────────────
#define BATTERY_ADC      4

#define SD_CS            38
#define SD_MOSI          39
#define SD_MISO          40
#define SD_SCLK          41
