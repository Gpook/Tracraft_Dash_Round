#pragma once

#include <Arduino_GFX_Library.h>

/**
 * Текст пропорциональными шрифтами.
 *
 * Встроенный в Arduino_GFX шрифт — битмап 6x8, растянутый целым множителем.
 * Именно он давал главное расхождение с редактором: цифры выглядели рублеными,
 * а размер прыгал ступенями по 8 пикселей. Здесь вместо него набор шрифтов
 * FreeSans в формате GFXfont: пропорциональные, с настоящими засечками формы.
 *
 * Произвольный кегль всё равно недоступен — глиф это битмап фиксированного
 * размера, увеличивать его можно только целым множителем. Поэтому доступна
 * ЛЕСТНИЦА высот (см. Text::ladder), и редактор обязан к ней прижимать
 * размеры, иначе на устройстве текст будет не того размера, что в превью.
 */
namespace Text {

/// Отношение высоты цифры к кеглю (em) у FreeSans.
///
/// В редакторе fontSize задаётся в тех же единицах, что у canvas — это em,
/// а не высота цифры. Внутри же всё считается по высоте цифр, потому что
/// именно она воспринимается как размер на приборной панели. Коэффициент
/// усреднён по четырём начертаниям: 13/18.3, 17/24.2, 25/35, 35/46.7.
constexpr float kCapPerEm = 0.72f;

/// Перевод кегля редактора в высоту цифры.
inline int capFromEm(float em) { return static_cast<int>(em * kCapPerEm + 0.5f); }

/// Начертание: конкретный шрифт плюс целый множитель увеличения.
struct Face {
    const GFXfont* font  = nullptr;
    uint8_t        scale = 1;
};

/// Высота цифры (cap height) для начертания, в пикселях.
int capPx(const Face& f);

/// Ближайшее доступное начертание для желаемой высоты цифр.
/// bold=false берёт светлое начертание — для подписей и единиц измерения.
Face pick(int targetCapPx, bool bold = true);

/// Полный список доступных высот цифр, по возрастанию.
/// Нужен редактору, чтобы предлагать только достижимые кегли.
/// Возвращает количество записей, заполняет out (не более max штук).
int ladder(int* out, int max, bool bold = true);

/// Ширина строки в пикселях для заданного начертания.
int width(const char* s, const Face& f);

/// Начертание, при котором строка вписывается в maxW x maxH.
Face fit(const char* s, int maxW, int maxH, bool bold = true);

/// Горизонтальное выравнивание в рамке.
enum class HA : uint8_t { Left, Center, Right };
/// Вертикальное выравнивание в рамке.
enum class VA : uint8_t { Top, Mid, Bottom };

/// Отрисовка строки в рамке с выравниванием.
///
/// Вертикаль считается по высоте цифр, а не по межстрочному интервалу:
/// иначе текст с цифрами визуально уезжает вверх из-за запаса под выносные
/// элементы букв.
void drawBox(Arduino_GFX* g, const char* s,
             int bx, int by, int bw, int bh,
             HA ha, VA va, const Face& f, uint16_t color);

/// Отрисовка строки с центром в точке.
void drawCentered(Arduino_GFX* g, const char* s, int cx, int cy,
                  const Face& f, uint16_t color);

/// Сброс шрифта на встроенный 6x8 — нужен только для аварийных сообщений,
/// которые печатаются до загрузки лейаута.
void useBuiltin(Arduino_GFX* g);

} // namespace Text
