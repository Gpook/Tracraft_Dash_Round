#pragma once

#include <Arduino_GFX_Library.h>

#include "aa_font.h"

/**
 * Текст на устройстве.
 *
 * История вопроса. Сначала здесь был встроенный в Arduino_GFX шрифт 6x8,
 * растянутый целым множителем, — цифры выглядели как восьмибитная графика.
 * Потом набор GFXfont (FreeSans): форма букв стала правильной, но глиф там
 * по-прежнему битовая маска без полутонов, поэтому края остались рваными, а
 * размер прыгал ступенями.
 *
 * Сейчас используются шрифты из include/fonts/Aa*.h: байт прозрачности на
 * пиксель, смешивание с фоном при выводе. Два следствия:
 *
 *   1. Края сглажены так же, как в canvas редактора.
 *   2. Размер задаётся дробным масштабом, а не целым множителем. Лестницы
 *      достижимых кеглей больше нет — любое значение из редактора
 *      воспроизводится точно, и функция ladder() из этого API убрана.
 *
 * Внутри всё считается по высоте цифр (cap height), а не по кеглю: именно
 * высота цифр воспринимается как «размер» на приборной панели, и по ней же
 * выравнивается текст по вертикали. Иначе строки с цифрами визуально уезжают
 * вверх из-за запаса под выносные элементы букв.
 */
namespace Text {

/// Отношение высоты цифры к кеглю (em) у Arial/Helvetica.
/// В редакторе props.fontSize задаётся в кеглях, как у canvas.
constexpr float kCapPerEm = 0.716f;

/// Перевод кегля редактора в высоту цифры.
inline int capFromEm(float em) { return static_cast<int>(em * kCapPerEm + 0.5f); }

/// Начертание: конкретный шрифт плюс дробный масштаб в формате 16.16.
struct Face {
    const AaFont* font  = nullptr;
    int32_t       scale = Aa::kOne;
};

/// Высота цифры для начертания, px.
int capPx(const Face& f);

/**
 * Начертание с заданной высотой цифр под конкретную строку.
 *
 * Масштаб получается точным, а вот базовый начерк зависит и от размера, и от
 * содержимого. Причина в том, что крупные начерки имеют урезанный алфавит:
 * глиф весит байт на пиксель, поэтому полный ASCII с высотой цифры 96px стоил
 * бы полмегабайта флеша при нулевой пользе.
 *
 * Поэтому строка проверяется на покрытие: берётся самый мелкий из начерков,
 * который её покрывает и при этом не требует растягивания. Если такого нет —
 * самый крупный из покрывающих. Строка не может остаться нарисованной
 * частично или не нарисованной вовсе.
 *
 * Строку передавать обязательно: без неё подбор по одному размеру отправил бы
 * крупную надпись в набор из одних цифр, и текст молча исчез бы с экрана.
 */
Face pick(const char* s, int targetCapPx, bool bold = true);

/// Ширина строки в пикселях.
int width(const char* s, const Face& f);

/// Начертание, при котором строка вписывается в maxW x maxH.
Face fit(const char* s, int maxW, int maxH, bool bold = true);

/// Горизонтальное выравнивание в рамке.
enum class HA : uint8_t { Left, Center, Right };
/// Вертикальное выравнивание в рамке.
enum class VA : uint8_t { Top, Mid, Bottom };

/// Отрисовка строки в рамке с выравниванием.
///
/// Аргумент g нужен для размеров полотна; сами пиксели пишутся напрямую в
/// фреймбуфер, потому что смешивание требует чтения фона.
void drawBox(Arduino_GFX* g, const char* s,
             int bx, int by, int bw, int bh,
             HA ha, VA va, const Face& f, uint16_t color);

/// Отрисовка строки с центром в точке.
void drawCentered(Arduino_GFX* g, const char* s, int cx, int cy,
                  const Face& f, uint16_t color);

/// Сброс на встроенный шрифт 6x8. Нужен только для аварийных сообщений,
/// которые печатаются до загрузки лейаута и до готовности фреймбуфера.
void useBuiltin(Arduino_GFX* g);

} // namespace Text
