/**
 * @file  display_hw.h
 * @brief Инициализация AMOLED-панели и полнокадрового фреймбуфера в PSRAM.
 *
 * Рисуем всегда в канву (gfx()), затем один раз за кадр вызываем flush().
 */

#pragma once

#include <Arduino_GFX_Library.h>

namespace Display {

/**
 * Поднимает QSPI-шину, панель и канву.
 * @return false — не удалось выделить фреймбуфер или инициализировать панель.
 */
bool begin();

/// Цель отрисовки: фреймбуфер 466x466 RGB565 в PSRAM.
Arduino_GFX* gfx();

/// Отправить кадр на панель.
void flush();

/// Заливка всего фреймбуфера одним цветом.
/// Быстрее gfx()->fillScreen(): пишет 32-битными словами напрямую в буфер.
void clear(uint16_t color);

/// Разовый замер на старте: скорость записи в PSRAM, время отправки кадра и
/// цена одного примитива. Печатает результат в Serial. Нужен, чтобы отличать
/// «медленный рендер» от «медленная шина» по числам, а не по догадкам.
void selfTest();

/**
 * Статический слой: копия кадра с одним только неподвижным содержимым.
 *
 * Смысл в том, что перерисовывать каждый кадр весь экран незачем. Фон и
 * виджеты, не зависящие от сигналов (подписи, картинки), рисуются один раз при
 * смене экрана и запоминаются здесь. Дальше каждый кадр из слоя копируются
 * только прямоугольники под движущимися виджетами — это восстанавливает под
 * ними фон, и полная очистка экрана становится не нужна.
 *
 * Выделение может не удаться; тогда staticLayerReady() вернёт false и
 * вызывающий должен вернуться к полной перерисовке.
 */
bool staticLayerReady();

/// Запомнить текущий кадр как статический слой.
void saveStaticLayer();

/// Скопировать прямоугольник из слоя в кадр. Клиппинг по границам внутри.
void restoreRect(int x, int y, int w, int h);

/// Скопировать весь слой в кадр. Нужно после полноэкранных оверлеев.
void restoreAll();

/**
 * Отправить на панель только полосу строк [y0, y0+h).
 *
 * Смысл в том, что отправка кадра — самая дорогая часть кадра, и платить за
 * неподвижные области незачем. Полоса берётся во всю ширину панели
 * намеренно: тогда её пиксели лежат в памяти непрерывно, и библиотека
 * отправляет всю полосу одним вызовом writePixels вместо построчных. Узкий
 * прямоугольник, наоборот, распался бы на транзакцию на строку — то есть в
 * ровно ту проблему, из-за которой отправка и была медленной.
 */
void flushRows(int y0, int h);

/**
 * Сколько микросекунд отправка простояла в ожидании шины с прошлого вызова.
 *
 * Отправка кадра состоит из двух работ, идущих параллельно: процессор готовит
 * очередной кусок пикселей, DMA отдаёт предыдущий. Общее время равно большей
 * из них, и без этого счётчика непонятно, какая именно упирается:
 *   - ожидание близко к нулю  -> медленнее готовим, узкое место в PSRAM;
 *   - ожидание почти всё время -> быстрее готовим, чем шина успевает, дальше
 *     ускорять отправку можно только частотой QSPI или числом строк.
 *
 * Счётчик сбрасывается при чтении.
 */
uint32_t busWaitedUs();

/// 0..255. Яркость всегда максимум во время езды — см. burn_in_protection.h.
void setBrightness(uint8_t v);

/// Размер фреймбуфера в байтах (для диагностики).
size_t framebufferBytes();

/// Сырой фреймбуфер 466x466 RGB565.
/// Нужен для эффектов, которых нет в Arduino_GFX: полупрозрачное затемнение
/// уже отрисованного кадра под всплывающим Warning и под shift-light flash.
uint16_t* framebuffer();

} // namespace Display
