/**
 * @file  widget_render.h
 * @brief Отрисовка виджетов лейаута в канву.
 *
 * Порт web/src/renderer/* на Arduino_GFX. Формулы и раскладка совпадают с
 * редактором, поэтому расхождение картинки на устройстве и в предпросмотре
 * означает баг, а не «другой рендер».
 *
 * Текст рисуется сглаженными шрифтами через модуль Text (см. text_render.h):
 * байт прозрачности на пиксель, дробный масштаб. Ограничения по набору
 * размеров нет — любой кегль из редактора воспроизводится точно.
 *
 * Геометрия (дуги, окружности, линии) по-прежнему рисуется примитивами
 * Arduino_GFX без сглаживания, поэтому их края здесь жёстче, чем на Canvas2D.
 */

#pragma once

#include <Arduino_GFX_Library.h>

namespace Render {

/// Всё, что нужно кадру помимо самого лейаута.
struct Frame {
    Arduino_GFX* gfx;       ///< цель отрисовки
    float        timeSec;   ///< секунды с момента старта (для мигания/анимаций)
    int16_t      shiftX;    ///< сдвиг сцены по X: burn-in плюс листание свайпом
    int16_t      shiftY;    ///< сдвиг сцены по Y
    uint16_t     bg;        ///< фон экрана: база для полупрозрачных подложек
};

/**
 * Что рисовать за проход.
 *
 * Экран делится на неподвижную часть (фон, подписи, картинки) и движущуюся
 * (всё, что зависит от сигналов). Неподвижную достаточно нарисовать один раз
 * при смене экрана — см. статический слой в display_hw.h. Разделение даёт
 * экономию не столько на самих подписях, сколько на том, что исчезает полная
 * очистка кадра: фон под движущимися виджетами восстанавливается
 * копированием из слоя.
 */
enum class Pass : uint8_t {
    All,      ///< всё подряд — используется во время свайпа
    Static,   ///< только неподвижное
    Dynamic,  ///< только зависящее от сигналов
};

/// Отрисовать виджеты экрана по возрастанию z.
///
/// Фон НЕ заливается: во время свайпа в один кадр рисуются два экрана со
/// сдвигом, и заливка внутри стёрла бы первый. Очистку делает вызывающий.
///
/// @return true, если был нарисован полноэкранный оверлей (авария или вспышка
///         шифт-лайта). Такой оверлей затрагивает пиксели за пределами рамки
///         виджета, поэтому следующий кадр обязан восстановить экран целиком,
///         а не только прямоугольники под виджетами.
bool screen(const Frame& f, uint8_t screenIdx, Pass pass = Pass::All);

/// Восстановить из статического слоя фон под всеми движущимися виджетами.
/// Вызывается перед Pass::Dynamic вместо очистки кадра.
void restoreDynamic(const Frame& f, uint8_t screenIdx);

/// Полоса строк, полуинтервал [y0, y1).
struct Band {
    int16_t y0;
    int16_t y1;
};

/// Максимум полос, которые имеет смысл различать. Каждая полоса — это своё
/// окно адресации на панели, и после нескольких штук выгода от экономии
/// строк перестаёт покрывать накладные расходы.
constexpr int kMaxBands = 6;

/**
 * Полосы строк, затронутые движущимися виджетами.
 *
 * Нужны для частичной отправки кадра: неподвижные строки на панель гнать
 * незачем. Пересекающиеся и близко стоящие полосы объединяются — разрыв в
 * несколько строк дешевле передать, чем заводить под него отдельное окно
 * адресации.
 *
 * @return количество заполненных полос
 */
int dirtyBands(const Frame& f, uint8_t screenIdx, Band* out, int max);

} // namespace Render
